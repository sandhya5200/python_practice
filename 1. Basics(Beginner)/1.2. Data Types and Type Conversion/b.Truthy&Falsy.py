# Truthy vs Falsy Values in Python

# Truthy values are values that Python considers True in a conditional statement.
# Examples include:
# - Non-zero numbers: 10, -5, 3.14
# - Non-empty strings: "Python", "Hello"
# - Non-empty lists: [1, 2, 3]
# - Non-empty tuples: (1, 2)
# - Non-empty dictionaries: {"name": "Sam"}
# - True


# Falsy values are values that Python considers False in a conditional statement.
# Examples include:
# - False
# - None
# - Zero integers: 0
# - Zero floats: 0.0
# - Empty strings: ""
# - Empty lists: []
# - Empty tuples: ()
# - Empty dictionaries: {}
# - Empty sets: set()
# - Zero complex numbers: 0j

